import { test, expect } from '@playwright/test'
import { collection, getDocs } from 'firebase/firestore'
// @ts-expect-error Local fixture scripts run directly as Node ESM, outside the app bundle.
import { seedPublicFixtures, changePublicFixture, withLocalPublicFixture } from '../scripts/seed-public.mjs'

test.beforeEach(async () => { await seedPublicFixtures() })
const addName = 'Adicionar Produto Essencial DEMO à sacola'
test('público: busca, categorias, sacola, reload, preço atual e separação de lojas', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  const before = await withLocalPublicFixture(async (db: import('firebase/firestore').Firestore) => ({
    stocks: (await getDocs(collection(db, 'stores/store-demo-a/products'))).docs.map(d => d.data().stock),
    movements: (await getDocs(collection(db, 'stores/store-demo-a/stockMovements'))).size,
  }))
  await page.goto('/loja/store-a-demo')
  await expect(page.getByRole('link', { name: 'Store Demo', exact: true })).toBeVisible()
  await expect(page.locator('.public-storefront').locator('..')).toHaveAttribute('data-store-theme', 'clean')
  const search = page.getByRole('searchbox', { name: 'Buscar produtos' })
  await search.fill('especial')
  await expect(page.getByRole('article')).toHaveCount(1)
  await expect(page.getByRole('heading', { name: 'Produto Especial DEMO' })).toBeVisible()
  await search.fill('')
  await page.getByRole('navigation', { name: 'Categorias' }).getByRole('button', { name: 'Coleção DEMO' }).click()
  await expect(page.getByRole('article')).toHaveCount(1)
  await page.getByRole('button', { name: 'Todos', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Adicionar Produto Indisponível DEMO à sacola' })).toBeDisabled()
  await page.getByRole('button', { name: addName }).click()
  const trigger = page.getByRole('button', { name: /Abrir sacola/ })
  await trigger.focus(); await page.keyboard.press('Enter')
  await page.getByRole('button', { name: 'Aumentar quantidade de Produto Essencial DEMO' }).click()
  await expect(page.getByLabel('Quantidade de Produto Essencial DEMO', { exact: true })).toHaveText('2')
  await expect(page.getByLabel('Subtotal da sacola')).toContainText('39,80')
  await expect(page.getByRole('button', { name: 'Aumentar quantidade de Produto Essencial DEMO' })).toBeDisabled()
  await page.getByRole('button', { name: 'Diminuir quantidade de Produto Essencial DEMO' }).click()
  await page.getByRole('button', { name: 'Remover Produto Essencial DEMO' }).click()
  await expect(page.getByRole('heading', { name: 'Sua sacola está vazia' })).toBeVisible()
  await page.keyboard.press('Escape'); await expect(trigger).toBeFocused()
  await page.getByRole('button', { name: addName }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Abrir sacola, 1 itens' })).toBeVisible()
  await changePublicFixture({ priceCents: 2990 })
  await page.reload(); await page.getByRole('button', { name: /Abrir sacola/ }).click()
  await expect(page.getByLabel('Subtotal da sacola')).toContainText('29,90')
  await page.keyboard.press('Escape')
  await page.goto('/loja/store-b-demo')
  await expect(page.getByRole('button', { name: 'Abrir sacola, 0 itens' })).toBeVisible()
  await page.getByRole('button', { name: addName }).click()
  await page.goto('/loja/store-a-demo')
  await expect(page.getByRole('button', { name: 'Abrir sacola, 1 itens' })).toBeVisible()
  await withLocalPublicFixture(async (db: import('firebase/firestore').Firestore) => {
    expect((await getDocs(collection(db, 'stores/store-demo-a/orders'))).size).toBe(0)
    expect((await getDocs(collection(db, 'stores/store-demo-a/products'))).docs.map(d => d.data().stock)).toEqual(before.stocks)
    expect((await getDocs(collection(db, 'stores/store-demo-a/stockMovements'))).size).toBe(before.movements)
  })
  expect(errors).toEqual([])
})

test('loja real em seis viewports, clean/dark, drawer, teclado e reduced motion', async ({ page }) => {
  await page.goto('/loja/store-a-demo')
  await page.getByRole('button', { name: addName }).click()
  for (const [width, height] of [[1440, 900], [1280, 800], [1024, 768], [768, 1024], [390, 844], [320, 720]]) {
    await page.setViewportSize({ width, height })
    await page.getByRole('link', { name: 'Store Demo', exact: true }).scrollIntoViewIfNeeded()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `output/playwright/phase6/store-${width}.png`, fullPage: true })
    await page.getByRole('button', { name: /Abrir sacola/ }).click()
    const dialog = page.getByRole('dialog', { name: 'Sua sacola' })
    await expect(dialog).toBeVisible()
    expect(await dialog.evaluate(el => { const rect = el.getBoundingClientRect(); return rect.left >= 0 && rect.right <= innerWidth && rect.height <= innerHeight })).toBe(true)
    await page.screenshot({ path: `output/playwright/phase6/cart-${width}.png`, fullPage: true })
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button', { name: /Abrir sacola/ })).toBeFocused()
  }
  await changePublicFixture({ themePreset: 'dark' })
  await page.reload()
  await expect(page.locator('.public-storefront').locator('..')).toHaveAttribute('data-store-theme', 'dark')
  await expect(page.getByRole('article')).toHaveCount(3)
  await page.screenshot({ path: 'output/playwright/phase6/store-dark-320.png', fullPage: true })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByRole('button', { name: /Abrir sacola/ }).click()
  await expect(page.getByRole('dialog')).toHaveAttribute('data-store-theme', 'dark')
  await page.screenshot({ path: 'output/playwright/phase6/cart-dark-320.png', fullPage: true })
  const remove = page.getByRole('button', { name: 'Remover Produto Essencial DEMO' })
  await remove.focus(); await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('button', { name: 'Fechar painel' })).toBeFocused()
  await page.keyboard.press('Tab'); await expect(remove).toBeFocused()
  await page.keyboard.press('Escape')
  expect(await page.getByRole('button', { name: addName }).evaluate(el => parseFloat(getComputedStyle(el).transitionDuration))).toBeLessThan(.001)
})
