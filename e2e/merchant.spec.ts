import { test, expect } from '@playwright/test'
// Local-only Node fixture provisioner. It is not part of the application bundle.
// @ts-expect-error Fixture script deliberately uses Node ESM without a build step.
import { seedLocalFixtures, demoCredentials } from '../scripts/seed-local.mjs'

test.beforeEach(async () => { await seedLocalFixtures({ reset: true }) })
async function login(page: import('@playwright/test').Page) {
  await page.goto('/painel')
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel('E-mail', { exact: true }).fill(demoCredentials.email)
  await page.getByLabel('Senha', { exact: true }).fill(demoCredentials.password)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `output/playwright/phase5/login-${page.viewportSize()!.width}.png`, fullPage: true })
  await page.getByRole('button', { name: 'Entrar no painel' }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Visão geral', exact: true })).toBeVisible()
}
async function go(page: import('@playwright/test').Page, name: string) {
  if (await page.getByRole('button', { name: 'Abrir menu' }).isVisible()) {
    await page.getByRole('button', { name: 'Abrir menu' }).click()
    await page.getByRole('navigation', { name: 'Menu móvel do lojista' }).getByRole('link', { name, exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
  } else await page.getByRole('navigation', { name: 'Menu do lojista', exact: true }).getByRole('link', { name, exact: true }).click()
}

test('login, categoria, produto, reload, edição, estados, arquivamento, reativação e logout reais', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await login(page)
  await go(page, 'Categorias')
  await page.getByLabel('Nome da categoria').fill('Categoria E2E DEMO')
  await page.getByRole('button', { name: 'Criar categoria', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Categoria E2E DEMO' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Categoria E2E DEMO' })).toBeVisible()
  await go(page, 'Produtos')
  await page.getByRole('button', { name: 'Novo produto', exact: true }).click()
  await page.getByLabel('Nome', { exact: true }).fill('Produto E2E DEMO')
  await page.getByLabel('Descrição', { exact: true }).fill('Descrição local')
  await page.getByLabel('Preço (R$)', { exact: true }).fill('19,90')
  await page.getByLabel('Categoria', { exact: true }).selectOption({ label: 'Categoria E2E DEMO' })
  await page.getByLabel('Quantidade em estoque').fill('3')
  await page.getByRole('button', { name: 'Salvar produto', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Sem imagem Produto E2E DEMO', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('cell', { name: 'Sem imagem Produto E2E DEMO', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Editar Produto E2E DEMO', exact: true }).click()
  await expect(page.getByLabel('Estoque atual')).toHaveValue('3')
  await page.getByLabel('Preço (R$)', { exact: true }).fill('1.299,90')
  await page.getByRole('button', { name: 'Salvar produto', exact: true }).click()
  await expect(page.getByRole('cell', { name: /1\.299,90/ })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('cell', { name: /1\.299,90/ })).toBeVisible()
  await page.setViewportSize({ width: 320, height: 720 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'output/playwright/phase5/products-populated-320.png', fullPage: true })
  await go(page, 'Categorias')
  await page.getByRole('button', { name: 'Arquivar Categoria E2E DEMO', exact: true }).click()
  const categoryDialog = page.getByRole('alertdialog', { name: 'Arquivar categoria?' })
  await categoryDialog.getByRole('button', { name: 'Arquivar', exact: true }).click()
  await expect(categoryDialog.getByRole('alert')).toBeVisible()
  await page.screenshot({ path: 'output/playwright/phase5/category-in-use-320.png', fullPage: true })
  await categoryDialog.getByRole('button', { name: 'Cancelar', exact: true }).focus()
  await page.keyboard.press('Space')
  await expect(categoryDialog).toHaveCount(0)
  await go(page, 'Produtos')
  await page.getByRole('button', { name: 'Inativar Produto E2E DEMO', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Inativo', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Arquivar Produto E2E DEMO', exact: true }).click()
  const dialog = page.getByRole('alertdialog', { name: 'Arquivar produto?' })
  await expect(dialog.getByRole('button', { name: 'Cancelar', exact: true })).toBeFocused()
  expect(await dialog.evaluate(el => { const box = el.getBoundingClientRect(); return box.left >= 0 && box.right <= innerWidth })).toBe(true)
  await page.screenshot({ path: 'output/playwright/phase5/archive-product-320.png', fullPage: true })
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: 'Arquivar', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('button', { name: 'Cancelar', exact: true })).toBeFocused()
  await dialog.getByRole('button', { name: 'Arquivar', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Arquivado', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Reativar Produto E2E DEMO', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Ativo', exact: true })).toBeVisible()
  await go(page, 'Minha Loja')
  await page.getByLabel('Nome da loja', { exact: true }).fill('Store A editada DEMO')
  await page.getByRole('button', { name: 'Salvar loja', exact: true }).click()
  await expect(page.getByText('Nome da loja atualizado.')).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Nome da loja', { exact: true })).toHaveValue('Store A editada DEMO')
  await page.getByRole('button', { name: 'Sair', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.goto('/painel/produtos')
  await expect(page).toHaveURL(/\/login$/)
  expect(errors).toEqual([])
})

test('seis viewports, menu mobile, formulários e movimento reduzido', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 720 })
  await login(page)
  for (const [width, height] of [[1440, 900], [1280, 800], [1024, 768], [768, 1024], [390, 844], [320, 720]]) {
    await page.setViewportSize({ width, height })
    await go(page, 'Dashboard')
    await expect(page.getByRole('heading', { name: 'Visão geral', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
    expect(await page.locator('img').evaluateAll(images => images.every(img => img instanceof HTMLImageElement && img.complete && img.naturalWidth > 0))).toBe(true)
    await page.screenshot({ path: `output/playwright/phase5/dashboard-${width}.png`, fullPage: true })
    await go(page, 'Categorias')
    await expect(page.getByLabel('Nome da categoria')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `output/playwright/phase5/categories-${width}.png`, fullPage: true })
    await go(page, 'Produtos')
    await page.getByRole('button', { name: 'Novo produto', exact: true }).click()
    await expect(page.getByLabel('Preço (R$)', { exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `output/playwright/phase5/product-form-${width}.png`, fullPage: true })
  }
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByRole('button', { name: 'Abrir menu' }).click()
  await expect(page.getByRole('dialog', { name: 'Menu do lojista' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Abrir menu' })).toBeFocused()
  const duration = await page.getByRole('button', { name: 'Abrir menu' }).evaluate(el => getComputedStyle(el).transitionDuration)
  expect(parseFloat(duration)).toBeLessThan(.001)
  await page.goto('/')
  await page.getByRole('button', { name: 'Verificar interface' }).click()
  await expect(page.getByRole('status')).toHaveText('Interface respondendo.')
  await page.getByRole('link', { name: 'Abrir Design System ATS 2.0' }).click()
  await expect(page.getByRole('heading', { name: 'Consistência para operar. Liberdade para cada marca.' })).toBeVisible()
  await page.getByRole('button', { name: 'Abrir painel', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Painel lateral' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Abrir painel', exact: true })).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
